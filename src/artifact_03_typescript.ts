import { Connection, PublicKey, Keypair } from "@solana/web3.js";
import { Program, AnchorProvider, Wallet, Idl, utils } from "@coral-xyz/anchor";
import axios from "axios";
import { Resend } from "resend";
import * as dotenv from "dotenv";
import * as crypto from "crypto";

dotenv.config();

const RESEND_API_KEY = process.env.RESEND_API_KEY || "re_test_000000000000000000000000";
const SLACK_WEBHOOK_URL = process.env.SLACK_WEBHOOK_URL || "";
const RPC_ENDPOINT = process.env.SOLANA_RPC_URL || "http://127.0.0.1:8899";
const PROGRAM_ID = new PublicKey(
  process.env.PROGRAM_ID || "Kssp111111111111111111111111111111111111111"
);
const AUDIT_EMAIL_TO = process.env.AUDIT_EMAIL_TO || "treasury-audit@krakow-dao.fi";

const resend = new Resend(RESEND_API_KEY);

interface StreamEventPayload {
  streamId: string;
  sender: string;
  recipient: string;
  amount: string;
  eventType: "STREAM_CREATED" | "MILESTONE_UNLOCKED" | "WITHDRAWAL" | "DISPUTE";
  txSignature: string;
  timestamp: string;
}

export class KsspEnterpriseAgent {
  private connection: Connection;
  private provider: AnchorProvider;
  private program: Program;

  constructor(payerKeypair: Keypair, idl: Idl) {
    this.connection = new Connection(RPC_ENDPOINT, {
      commitment: "confirmed",
      wsEndpoint: RPC_ENDPOINT.replace("http", "ws"),
    });
    const wallet = new Wallet(payerKeypair);
    this.provider = new AnchorProvider(this.connection, wallet, {
      commitment: "confirmed",
    });
    this.program = new Program(idl, this.provider);
  }

  /**
   * Dispatches cryptographic transaction summary via Resend enterprise email
   */
  public async dispatchAuditEmail(payload: StreamEventPayload): Promise<void> {
    if (!process.env.RESEND_API_KEY) {
      console.log("[Resend Agent Mock] Dispatched email payload:", payload);
      return;
    }

    try {
      const emailHtml = `
        <div style="font-family: Arial, sans-serif; padding: 20px; background-color: #f7f9fa; color: #1e293b;">
          <h2 style="color: #0284c7; border-bottom: 2px solid #0284c7; padding-bottom: 8px;">
            Kraków Sentinel Protocol: Settlement Notification
          </h2>
          <p>An on-chain settlement transition has been cryptographically confirmed on Solana.</p>
          <table style="width: 100%; border-collapse: collapse; margin-top: 15px;">
            <tr><td style="padding: 8px; font-weight: bold;">Event Type:</td><td>${payload.eventType}</td></tr>
            <tr><td style="padding: 8px; font-weight: bold;">Stream Identifier:</td><td>#${payload.streamId}</td></tr>
            <tr><td style="padding: 8px; font-weight: bold;">Settled Amount:</td><td>${payload.amount} SPL Tokens</td></tr>
            <tr><td style="padding: 8px; font-weight: bold;">Sender PDA:</td><td><code>${payload.sender}</code></td></tr>
            <tr><td style="padding: 8px; font-weight: bold;">Recipient PDA:</td><td><code>${payload.recipient}</code></td></tr>
            <tr><td style="padding: 8px; font-weight: bold;">Solana Tx Hash:</td><td><code>${payload.txSignature}</code></td></tr>
            <tr><td style="padding: 8px; font-weight: bold;">Attestation UTC:</td><td>${payload.timestamp}</td></tr>
          </table>
          <hr style="margin-top: 25px; border: 0; border-top: 1px solid #cbd5e1;" />
          <p style="font-size: 11px; color: #64748b;">Autonomous notification generated by Kraków Sentinel Daemon v1.0.0.</p>
        </div>
      `;

      await resend.emails.send({
        from: "Krakow Sentinel <system@resend.dev>",
        to: [AUDIT_EMAIL_TO],
        subject: `[KSSP Audit] ${payload.eventType} - Stream #${payload.streamId}`,
        html: emailHtml,
      });
      console.log(`[Resend] Successfully dispatched audit receipt for Stream #${payload.streamId}`);
    } catch (err) {
      console.error("[Resend Error] Failed to send enterprise email:", err);
    }
  }

  /**
   * Dispatches instant webhook notification to SecOps Slack channel
   */
  public async dispatchSlackAlert(payload: StreamEventPayload): Promise<void> {
    if (!SLACK_WEBHOOK_URL) {
      console.log("[Slack Agent Mock] Alert dispatched:", payload);
      return;
    }

    try {
      const color =
        payload.eventType === "DISPUTE"
          ? "#ef4444"
          : payload.eventType === "MILESTONE_UNLOCKED"
          ? "#22c55e"
          : "#3b82f6";

      const messageBody = {
        attachments: [
          {
            color,
            title: `Solana Sentinel Alert: ${payload.eventType}`,
            fields: [
              { title: "Stream ID", value: payload.streamId, short: true },
              { title: "Amount", value: payload.amount, short: true },
              { title: "Sender", value: payload.sender.slice(0, 8) + "...", short: true },
              { title: "Recipient", value: payload.recipient.slice(0, 8) + "...", short: true },
              { title: "Tx Signature", value: payload.txSignature, short: false },
            ],
            footer: "Kraków Sentinel Stream Protocol | Solana Sealevel Engine",
            ts: Math.floor(Date.now() / 1000),
          },
        ],
      };

      await axios.post(SLACK_WEBHOOK_URL, messageBody);
      console.log(`[Slack] Alert sent for Stream #${payload.streamId}`);
    } catch (err) {
      console.error("[Slack Error] Webhook delivery failed:", err);
    }
  }

  /**
   * Deterministic SHA-256 deliverable helper for milestone verification
   */
  public static generateMilestoneHash(rawDeliverablePayload: string): Buffer {
    return crypto.createHash("sha256").update(rawDeliverablePayload).digest();
  }

  /**
   * Autonomous Event Stream Watcher
   */
  public initializeEventListener(): void {
    console.log(`[KSSP Worker] Subscribing to program events for ID: ${PROGRAM_ID.toBase58()}`);

    this.program.addEventListener("MilestoneUnlockedEvent", async (event: any, slot: number, signature: string) => {
      console.log(`[Event: MilestoneUnlocked] Stream: ${event.streamId.toString()} | Amount: ${event.amountUnlocked.toString()}`);
      const payload: StreamEventPayload = {
        streamId: event.streamId.toString(),
        sender: "N/A",
        recipient: "N/A",
        amount: event.amountUnlocked.toString(),
        eventType: "MILESTONE_UNLOCKED",
        txSignature: signature,
        timestamp: new Date().toISOString(),
      };
      await Promise.all([this.dispatchAuditEmail(payload), this.dispatchSlackAlert(payload)]);
    });

    this.program.addEventListener("DisputeOpenedEvent", async (event: any, slot: number, signature: string) => {
      console.warn(`[Event: DisputeOpened] Stream: ${event.streamId.toString()} raised by ${event.initiator.toBase58()}`);
      const payload: StreamEventPayload = {
        streamId: event.streamId.toString(),
        sender: event.initiator.toBase58(),
        recipient: "DISPUTED",
        amount: "0",
        eventType: "DISPUTE",
        txSignature: signature,
        timestamp: new Date().toISOString(),
      };
      await Promise.all([this.dispatchAuditEmail(payload), this.dispatchSlackAlert(payload)]);
    });
  }
}